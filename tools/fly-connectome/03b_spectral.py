"""Photoreceptor catches of the scene materials (what each fly photoreceptor type
absorbs from each colour of the board), written to src/features/fly-connect4/vision/spectral.json.

  sRGB colour (vision/palette.json)
    -> reflectance spectrum, Mallett & Yuksel 2019 (colour-science; physically valid
       reflectance in [0, 1] for every sRGB colour)
    x illuminant CIE D65 (daylight), converted to photon flux (E * lambda)
    x photoreceptor spectral sensitivity: Govardovskii et al. 2000 A1 template
      (alpha + beta bands) at the peaks measured in vivo by Sharkey et al. 2020
      (Sci Rep 10:18242): Rh1 (R1-6) 478 nm, Rh3 (R7p) 330, Rh4 (R7y) 355,
      Rh5 (R8p) 435, Rh6 (R8y) 600 nm.
  -> quantum catch relative to a perfect white reflector.

Integration is limited to 380-780 nm: the UV reflectance of the plastics is unknown
(sRGB says nothing about it), so R7 channels only see the long-wavelength tails of
their pigments. The UV sensitising pigment of Rh1 is therefore irrelevant here.
Only R1-6 feeds the model (they are the photoreceptors presynaptic to L1-L3).
"""

import json
from pathlib import Path

import colour
import numpy as np

HERE = Path(__file__).parent
VISION = HERE.parent.parent / "src" / "features" / "fly-connect4" / "vision"

PEAKS_NM = {"R1-6": 478.0, "R7p": 330.0, "R7y": 355.0, "R8p": 435.0, "R8y": 600.0}
WL = np.arange(380.0, 781.0, 5.0)


def govardovskii_a1(lmax: float, wl: np.ndarray) -> np.ndarray:
    """Govardovskii et al. 2000, Vis Neurosci 17:509, A1 pigment template (alpha + beta)."""
    x = lmax / wl
    a = 0.8795 + 0.0459 * np.exp(-((lmax - 300.0) ** 2) / 11940.0)
    alpha = 1.0 / (np.exp(69.7 * (a - x)) + np.exp(28.0 * (0.922 - x)) + np.exp(-14.9 * (1.104 - x)) + 0.674)
    lmb = 189.0 + 0.315 * lmax
    bb = -40.5 + 0.195 * lmax
    beta = 0.26 * np.exp(-(((wl - lmb) / bb) ** 2))
    return alpha + beta


def reflectance(hex_colour: str) -> np.ndarray:
    srgb = np.array([int(hex_colour[i:i + 2], 16) / 255.0 for i in (1, 3, 5)])
    linear = colour.cctf_decoding(srgb, function="sRGB")
    sd = colour.recovery.RGB_to_sd_Mallett2019(linear)
    return np.clip(sd.copy().align(colour.SpectralShape(380, 780, 5)).values, 0.0, 1.0)


def main() -> None:
    palette = {k: v for k, v in json.loads((VISION / "palette.json").read_text()).items() if not k.startswith("_")}
    d65 = colour.SDS_ILLUMINANTS["D65"].copy().align(colour.SpectralShape(380, 780, 5)).values
    photons = d65 * WL  # energy -> photon flux (up to a constant)
    sens = {r: govardovskii_a1(l, WL) for r, l in PEAKS_NM.items()}
    catches = {}
    for name, hx in palette.items():
        refl = reflectance(hx)
        catches[name] = {r: round(float(np.sum(s * photons * refl) / np.sum(s * photons)), 5) for r, s in sens.items()}
    out = {
        "_comment": "Generated by tools/fly-connectome/03b_spectral.py; do not edit.",
        "illuminant": "CIE D65",
        "wavelength_range_nm": [380, 780],
        "peaks_nm": PEAKS_NM,
        "catch_relative_to_white": catches,
    }
    (VISION / "spectral.json").write_text(json.dumps(out, indent=1) + "\n")
    print(json.dumps(catches, indent=1))


if __name__ == "__main__":
    main()
